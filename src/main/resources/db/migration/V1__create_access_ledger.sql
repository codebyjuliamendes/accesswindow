-- Portable between PostgreSQL and H2 (MODE=PostgreSQL), which backs the test suite.
CREATE TABLE access_grant (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR(254) NOT NULL,
    resource    VARCHAR(120) NOT NULL,
    role        VARCHAR(60)  NOT NULL,
    owner       VARCHAR(120) NOT NULL,
    reason      VARCHAR(500) NOT NULL,
    expires_at  DATE         NOT NULL,
    state       VARCHAR(16)  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    version     INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT access_grant_state_chk CHECK (state IN ('ACTIVE', 'REVOKED'))
);

CREATE INDEX access_grant_review_idx ON access_grant (state, expires_at);

CREATE TABLE access_event (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grant_id            BIGINT       NOT NULL REFERENCES access_grant (id),
    type                VARCHAR(16)  NOT NULL,
    actor               VARCHAR(120) NOT NULL,
    note                VARCHAR(500),
    previous_expires_at DATE,
    new_expires_at      DATE,
    occurred_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT access_event_type_chk CHECK (type IN ('CREATED', 'REVOKED', 'RENEWED'))
);

CREATE INDEX access_event_grant_idx ON access_event (grant_id, occurred_at);
